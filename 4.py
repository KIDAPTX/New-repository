import sys
import io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

"""
======================================================
Python 第四课：循环 (for / while)
======================================================
"""

# ============================================
# 一、for 循环 —— 遍历列表
# ============================================
print("--- for 遍历列表 ---")

fruits = ["苹果", "香蕉", "橘子", "葡萄"]

for fruit in fruits:
    print(f"我喜欢吃{fruit}")

# ============================================
# 二、for 循环 —— 遍历字符串
# ============================================
print("\n--- for 遍历字符串 ---")

word = "Python"
for char in word:
    print(char, end=" ")  # end=" " 让打印不换行
print()  # 最后换行

# ============================================
# 三、range() 函数（生成数字序列）
# ============================================
print("\n--- range() 函数 ---")

# range(n)：0 到 n-1
print("range(5):")
for i in range(5):
    print(i, end=" ")
print()

# range(开始, 结束)：包左不包右
print("range(2, 7):")
for i in range(2, 7):
    print(i, end=" ")
print()

# range(开始, 结束, 步长)
print("range(1, 10, 2):")
for i in range(1, 10, 2):
    print(i, end=" ")
print()

# ============================================
# 四、while 循环（条件为真就一直执行）
# ============================================
print("\n--- while 循环 ---")

count = 1
while count <= 5:
    print(f"第{count}次执行")
    count += 1  # 相当于 count = count + 1，千万别忘！否则死循环

# ============================================
# 五、break（跳出整个循环）
# ============================================
print("\n--- break ---")

for i in range(1, 10):
    if i == 5:
        print("遇到5，退出循环！")
        break
    print(i, end=" ")
print()

# ============================================
# 六、continue（跳过本次，继续下一次）
# ============================================
print("\n--- continue ---")

for i in range(1, 8):
    if i == 4:
        continue  # 跳过 4
    print(i, end=" ")
print()

# ============================================
# 七、用 enumerate() 同时获取索引和值
# ============================================
print("\n--- enumerate() ---")

colors = ["红", "黄", "蓝"]
for index, color in enumerate(colors):
    print(f"第{index}个是{color}")

# ============================================
# 八、嵌套循环
# ============================================
print("\n--- 嵌套循环 ---")

for i in range(1, 4):
    for j in range(1, 4):
        print(f"({i}, {j})", end=" ")
    print()  # 内层循环结束换行

# ============================================
# 九、while 实现用户输入循环（实战）
