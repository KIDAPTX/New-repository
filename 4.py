# ============================================
# 十、综合练习：九九乘法表
# ============================================
print("\n--- 九九乘法表 ---")

for i in range(1, 10):
    for j in range(1, i + 1):
        print(f"{j}×{i}={i * j:2}", end="  ")  # :2 占2位对齐
    print()  # 换行

print("\n第四课结束！循环是编程最强大的工具之一~")
